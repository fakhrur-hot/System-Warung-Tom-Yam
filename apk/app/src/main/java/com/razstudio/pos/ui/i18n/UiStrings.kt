/**
 * In-app UI strings, resolved for the active [AppLanguage]. This is how the app's own
 * chrome (not just menu-item names) becomes translatable in all 5 languages, without
 * depending on Android resource locale switching (which only ever shipped EN/BM).
 *
 * Bahasa Malaysia is the authored source (matches [AppLanguage] / menu-item naming);
 * English, 中文, தமிழ், and ไทย are maintained alongside it. Every screen that renders
 * user-facing text should read from here rather than hardcoding an English literal.
 *
 * Split into 5 [UiStringsGroup1]..[UiStringsGroup5] data classes because a single
 * ~255-field data class blew past the DEX `invoke-direct/range` register limit (254 args +
 * `this`), crashing every screen at launch with a VerifyError. [UiStrings] itself stays a
 * thin wrapper with one delegated `val` per field, so every existing call site
 * (`strings.tableView`, `strings.addItemTitle`, etc.) keeps working completely unchanged —
 * only this file's internals changed. When adding new fields, prefer the smallest existing
 * group with room left, or start a new group, rather than growing one group past ~50 fields.
 */
