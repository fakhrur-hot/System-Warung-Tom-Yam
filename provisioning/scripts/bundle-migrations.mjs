// Reads supabase/migrations/*.sql from the monorepo root and emits a plain TS module the
// Cloudflare Pages Function can import. Cloudflare Pages' Functions bundler does not reliably
// support raw-text file imports across a monorepo boundary, so this generates a committed-shape
// TS file instead of relying on bundler-specific asset-import config — a plain `import` a normal
// TypeScript toolchain understands, no special loader needed.
//
// Run via `npm run generate` (part of `npm run build`), NOT committed — see .gitignore.

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const migrationsDir = path.join(here, '..', '..', 'supabase', 'migrations')
const outDir = path.join(here, '..', 'functions', '_generated')
const outFile = path.join(outDir, 'migrations.ts')

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()

if (files.length === 0) {
  console.error(`No .sql files found in ${migrationsDir}`)
  process.exit(1)
}

const entries = files.map((file) => {
  const sql = readFileSync(path.join(migrationsDir, file), 'utf-8')
  return { file, sql }
})

mkdirSync(outDir, { recursive: true })
writeFileSync(
  outFile,
  `// GENERATED by scripts/bundle-migrations.mjs — do not edit by hand.\n` +
    `// Source: supabase/migrations/*.sql, bundled at Wizard build time so the Cloudflare\n` +
    `// Pages Function has no cross-monorepo filesystem dependency at request time.\n\n` +
    `export interface MigrationEntry {\n  file: string\n  sql: string\n}\n\n` +
    `export const MIGRATIONS: MigrationEntry[] = ${JSON.stringify(entries, null, 2)}\n`,
  'utf-8',
)

console.log(`Bundled ${entries.length} migration(s) -> ${path.relative(process.cwd(), outFile)}`)
for (const e of entries) console.log(`  - ${e.file} (${e.sql.length} bytes)`)
