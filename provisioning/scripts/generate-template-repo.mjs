// Reads template-repo.properties from the monorepo root and emits a TS module the Pages Functions
// can import, so the Wizard knows which repository a café's Pages site is created from without that
// answer living in a hand-set environment variable.
//
// ### Why generated rather than committed here
//
// The same two values are also compiled into the APK (see apk/app/build.gradle.kts). If the Wizard
// kept its own copy, the two could disagree, and the failure would be quiet and strange: a café whose
// website deploys from one repo while its menu presets and affiliate catalog are fetched from another.
// One committed properties file at the root, both sides derived from it, no possible drift — the same
// reasoning as scripts/bundle-migrations.mjs, and the output is likewise gitignored.
//
// Run via `npm run generate` (part of `npm run build`), NOT committed — see .gitignore.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const propsFile = path.join(here, '..', '..', 'template-repo.properties')
const outDir = path.join(here, '..', 'functions', '_generated')
const outFile = path.join(outDir, 'template-repo.ts')

let raw
try {
  raw = readFileSync(propsFile, 'utf-8')
} catch {
  console.error(
    `template-repo.properties not found at ${propsFile}. It is committed at the monorepo root — ` +
      `if it is missing, this is not a full checkout.`,
  )
  process.exit(1)
}

// Minimal .properties parsing: KEY=VALUE, # comments, blank lines. The file is ours and stays simple,
// so a full parser would only add a dependency for no behaviour.
const props = {}
for (const line of raw.split(/\r?\n/)) {
  const trimmed = line.trim()
  if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('!')) continue
  const eq = trimmed.indexOf('=')
  if (eq === -1) continue
  props[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim()
}

const owner = props.RAZSTUDIO_GITHUB_OWNER
const repo = props.RAZSTUDIO_GITHUB_REPO
if (!owner || !repo) {
  console.error(
    `template-repo.properties must define RAZSTUDIO_GITHUB_OWNER and RAZSTUDIO_GITHUB_REPO. ` +
      `Found: owner=${owner ?? '(missing)'}, repo=${repo ?? '(missing)'}`,
  )
  process.exit(1)
}

mkdirSync(outDir, { recursive: true })
writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-template-repo.mjs — do not edit by hand.\n` +
    `// Source: template-repo.properties at the monorepo root.\n\n` +
    `export const TEMPLATE_GITHUB_OWNER = ${JSON.stringify(owner)}\n` +
    `export const TEMPLATE_GITHUB_REPO = ${JSON.stringify(repo)}\n`,
  'utf-8',
)

console.log(`generate-template-repo: ${owner}/${repo} -> functions/_generated/template-repo.ts`)
